/**
 * What the briefing *is*, which is a separate question from what state it is
 * in. You classified these: six projects and one research effort. Keeping
 * it apart from `status` is the point. `RESEARCH` used to be a status value,
 * which made it impossible to say that a piece of research was also active.
 */
export type ProjectKind = 'PROJECT' | 'RESEARCH';

/**
 * `DELIVERED` is a fourth value beyond the brief's three: a costed network
 * redesign is handed over, not deployed or archived, and calling it either
 * would be wrong.
 *
 * `COMPLETE` is a fifth: the work is done and is not being continued. You
 * told me the study coach and the surveillance research had both finished,
 * and none of the other four says that. `DEPLOYED` would claim they are
 * running somewhere, `DELIVERED` would claim they were handed to someone, and
 * `ARCHIVED` would say they were put down rather than finished. Say the word
 * if either is really one of those three and I will move it.
 *
 * `CLASSIFIED` is a sixth, and it is the one value here that is not a guess.
 * Every other badge describes where a project got to; this one says the
 * question is not being answered. It is its own status rather than a flag
 * beside one, because any of the other four would be a fact published about
 * a briefing that publishes no facts.
 */
export type ProjectStatus =
  'ACTIVE' | 'COMPLETE' | 'DEPLOYED' | 'DELIVERED' | 'ARCHIVED' | 'CLASSIFIED';

/**
 * A screenshot of the thing running.
 *
 * Generated by `scripts/process-media.py` from the originals in `assets/`.
 * Both dimensions ship on the element: these sit well below the fold and
 * load lazily, so without a reserved box every one of them is a layout shift
 * arriving mid scroll.
 */
export type ProjectMedia = {
  src: string;
  width: number;
  height: number;
  /** Describes the screenshot for anyone who cannot see it. */
  alt: string;
  /**
   * Two or three words under the picture in the briefing panel. It used to
   * read `capture · briefing_04`, which was fine while a project had one
   * picture and useless the moment one had two.
   */
  label: string;
};

export type Project = {
  id: string;
  /** Classification stamp, e.g. `BRIEFING_01`. */
  index: string;
  title: string;
  /** Project or research. Set by you. */
  kind: ProjectKind;
  /** My framing, not supplied copy. */
  tagline: string;
  status: ProjectStatus;
  /** false renders a dev only marker warning that the badge above is a guess. */
  statusConfirmed: boolean;
  /** Named tools and techniques, all from the brief. */
  stack: string[];
  /** What the briefing actually does. From the brief. */
  capabilities: string[];
  /** One paragraph for the expanded briefing. */
  brief: string;
  /**
   * Captures, in the order they should be read. The card shows the first and
   * only the first, clamped to 240px tall, because a card is a thumbnail of a
   * briefing rather than a gallery; the briefing panel shows all of them
   * whole. Put the one that proves the thing first.
   */
  media: ProjectMedia[];
  repo: string | null;
  demo: string | null;
};

