/**
 * Battle Station: competition record and open source activity.
 *
 * Two results are now on the wall. `BADGE_SLOTS` is still 4, so the rest are
 * **locked slots** rather than invented entries. That is both honest and the
 * normal visual language of an achievement system. Add entries below and each
 * one takes the next slot.
 *
 * Same rule for the counters: every number here is either derived from data
 * that already exists on this site, or `null`. A `null` renders `--` and a
 * `[ tbc ]` label instead of counting up to a figure nobody supplied. Dates
 * are the exception now: a missing one renders nothing at all, because a
 * placeholder under every badge was pointing at a gap rather than filling
 * one.
 */

/** Drives the frame, the glow and the unlock animation. */
export type Rarity = 'legendary' | 'rare' | 'standard';

export type Achievement = {
  id: string;
  /** Competition or programme. */
  event: string;
  /** What was won or reached. */
  result: string;
  rarity: Rarity;
  /** Renders only when there is one. No dates have been supplied. */
  date: string | null;
  /**
   * A few words under the badge, at badge width. Keep it short: the column is
   * 128px and anything longer than about three words becomes a six line
   * paragraph that pushes the row out of alignment.
   */
  note: string | null;
  /** The organising body, rendered as the last line under its own badge. */
  organiser: string | null;
  /**
   * One line above the photographs, for the context a 128px badge column
   * cannot hold. `null` when there is nothing to add.
   */
  fieldNote: string | null;
  /**
   * Pictures from the event, shown in the field record panel under the wall.
   * An empty array renders no panel at all, which is why an event with no
   * pictures costs the layout nothing.
   */
  images: AchievementImage[];
  /**
   * Who took the photographs, as one line under them. Required whenever they
   * are somebody else's work, which the organiser's are. It sits under the
   * photographs and above any capture, because a screenshot of a scoreboard
   * is nobody's photograph.
   */
  imageCredit: string | null;
};

/**
 * Generated by `scripts/process-media.py`. Both dimensions ship on the
 * element so the panel reserves its box before the bytes land.
 */
export type AchievementImage = {
  src: string;
  width: number;
  height: number;
  /**
   * A `photo` is somebody's camera: cropped to a shared shape, desaturated
   * at rest, captioned over the picture, and grouped two to a row. A
   * `capture` is a screenshot: it keeps its own shape and its own colours,
   * runs the full width, and is captioned underneath, because an overlay
   * would sit on top of the last row of a table.
   */
  kind: 'photo' | 'capture';
  /** Describes the picture, for a reader who cannot see it. */
  alt: string;
  /** Three or four words. */
  caption: string;
};

